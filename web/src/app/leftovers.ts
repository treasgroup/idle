const ASK = /(остал(ся|ась|ось|ись)|остатк|после праздник|после нового года|куда деть|куда девать|что сделать с|что делать с|сколько хранится|можно ли хранить)/;

/** «осталось оливье, что с ним делать» → how long it keeps and ideas; null when it is not such a question. */
export function leftoverAnswer(text: string): { text: string; options?: ChatOption[] } | null {
  const t = text.toLowerCase().replace(/ё/g, "е");
  if (!ASK.test(t)) return null;
  const hit = ITEMS.filter((x) => x.re.test(t));
  if (!hit.length) {
    if (!/праздник|нового года|новогодн|стола/.test(t)) return null;
    return {
      text: "После праздника: салаты с майонезом — съесть за сутки, мясо и птица хранятся 3–4 дня, холодец — до 5 дней. Напишите, что осталось, — подскажу, что из этого сделать.",
      options: [{ label: "Осталось мясо", text: "осталось запечённое мясо" }, { label: "Осталась курица", text: "осталась курица" }, { label: "Осталась нарезка", text: "осталась колбаса и сыр" }],
    };
  }
  const x = hit[0];
  return { text: x.keeps + " " + x.ideas, ...(x.options ? { options: x.options } : {}) };
}
