export const MEASURE: MeasurePage[] = DENSITY.map(([, label, glass, tbsp, tsp]) => {
  const m = MEASURE_META[label];
  if (!m) throw new Error("skolko: no page for «" + label + "»");
  return { slug: m.slug, label, gen: m.gen, ins: m.ins, glass, tbsp, tsp, unit: LIQUID.has(label) ? "мл" : "г", ing: m.ing };
});

